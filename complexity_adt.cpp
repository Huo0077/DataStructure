    cout << "  f(n) = Θ(n⁰) = Θ(1) → 情况 2 → T(n) = Θ(log n)" << endl;

    // ==================== 空间复杂度演示 ====================
    cout << "\n>>> 空间复杂度对比" << endl;
    cout << "  冒泡排序:     O(1) — 只需要几个临时变量" << endl;
